type Lang = 'vi' | 'en';

let overrideLang: Lang | null = null;

export const getLang = (): Lang => overrideLang ?? getPreferredLang();

export const setLang = (lang: Lang | null) => {
  overrideLang = lang;
};

const getPreferredLang = (): Lang => {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale;
    if (typeof locale === 'string' && locale.toLowerCase().startsWith('vi')) return 'vi';
  } catch {
    // ignore
  }
  return 'en';
};

