export type TranslationKey = keyof typeof dictionaries.en;

export type AppLang = Lang;

// Accept string keys to simplify incremental rollout.
export const t = (key: string) => {
  const lang = getLang();
  return (dictionaries as any)[lang]?.[key] ?? (dictionaries as any).en?.[key] ?? key;
};
